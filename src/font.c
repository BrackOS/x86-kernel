void font_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    unsigned char idx = (unsigned char)c;
    if (idx >= FONT_CHAR_COUNT) idx = '?';
    
    const uint8_t *glyph = font_data[idx];
    
    for (int dy = 0; dy < FONT_HEIGHT; dy++) {
        uint8_t row = glyph[dy];
        for (int dx = 0; dx < FONT_WIDTH; dx++) {
            uint32_t color = (row & (1 << (7 - dx))) ? fg : bg;
            fb_set_pixel(x + dx, y + dy, color);
        }
    }
}

void font_draw_string(int x, int y, const char *str, uint32_t fg, uint32_t bg) {
    int cx = x;
    while (*str) {
        font_draw_char(cx, y, *str, fg, bg);
        cx += FONT_WIDTH;
        str++;
    }
}
